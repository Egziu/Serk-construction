#!/usr/bin/env python3
"""Generates docs/release/REMEDIATION_REGISTER.yaml from docs/audit/ISSUE_REGISTER.md
(the single place findings are recorded) so the two can never disagree.

One entry per corrective action, carrying: owner, the tests that prove it,
the evidence, and a closure decision. The closure decision never claims more
than the register: AI-verified fixes still await human review, accepted
residual risks need a named human risk owner, and OPEN/BLOCKED items stay
open. Usage: python3 tools/remediation_register.py
"""
import json, os, re, subprocess

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = "docs/audit/ISSUE_REGISTER.md"
commit = subprocess.check_output(["git", "-C", ROOT, "rev-parse", "--short", "HEAD"], text=True).strip()
text = open(os.path.join(ROOT, SRC), encoding="utf-8").read()

def cells(line):
    # split a markdown table row on unescaped pipes outside backticks
    out, cur, tick = [], "", False
    for ch in line.strip().strip("|"):
        if ch == "`":
            tick = not tick
        if ch == "|" and not tick:
            out.append(cur.strip()); cur = ""
        else:
            cur += ch
    out.append(cur.strip())
    return out

section, header, items = "", None, []
for line in text.splitlines():
    if line.startswith("#"):
        section, header = line.lstrip("#").strip(), None
        continue
    if not line.startswith("|"):
        header = None if not line.strip() else header
        continue
    c = cells(line)
    if header is None:
        header = [h.lower() for h in c]
        continue
    if set(line) <= set("|-: "):
        continue
    row = dict(zip(header, c))
    iid = row.get("id", "").strip("*` ")
    if not iid:
        continue
    status = re.sub(r"\*", "", row.get("status", "")).strip()
    s = status.upper()
    if s.startswith("CLOSED") and "EXPLAINED" in s:
        decision = "closed: explained (no defect)"
    elif s.startswith("CLOSED") and "PREVENTED" in (row.get("sev.", "") + row.get("severity", "")).upper():
        decision = "closed: defect prevented before release"
    elif s.startswith("CLOSED") and "AI-VERIFIED" in s:
        decision = "closed by the delivering team (AI-verified with executed tests); awaiting independent human review"
    elif s.startswith("CLOSED"):
        decision = "closed with executed regression tests; awaiting independent human review"
    elif s.startswith("ACCEPTED"):
        decision = "accepted residual risk: REQUIRES a named human risk owner to accept"
    elif s.startswith("PARTIAL"):
        decision = "open: partially remediated"
    elif s.startswith("BLOCKED"):
        decision = "open: blocked (see blocker)"
    else:
        decision = "open"
    items.append({
        "id": iid,
        "source_section": section,
        "severity": row.get("sev.", row.get("severity", "")).strip("* "),
        "register_status": status,
        "finding": row.get("finding", row.get("root cause (v0.1.0)", "")),
        "corrective_action": row.get("fix", row.get("fix (where)", "")),
        "tests": row.get("test", row.get("regression tests", row.get("evidence", ""))),
        "evidence": row.get("evidence", row.get("test", "")),
        "residual_risk": row.get("residual risk", ""),
        "owner": "SERK engineering (delivering AI agent); accountable human owner: UNASSIGNED",
        "closure_decision": decision,
        "human_signoff": "not given",
    })

ids = [i["id"] for i in items]
dups = sorted({i for i in ids if ids.count(i) > 1})
if dups:
    raise SystemExit("duplicate IDs in the issue register: " + ", ".join(dups))
open_items = [i for i in items if i["closure_decision"].startswith("open")]
lines = [f"# Generated by tools/remediation_register.py from {SRC} at commit {commit}. Do not edit by hand.",
         "# No entry is closed by human review: every closure below is by the delivering team with executed tests,",
         "# and awaits independent human review. Production remains NO-GO.",
         f"source: {SRC}", f"commit: {commit}",
         f"counts: {{total: {len(items)}, open: {len(open_items)}, accepted_residual: {sum(1 for i in items if i['closure_decision'].startswith('accepted'))}}}",
         "items:"]
for i in items:
    lines.append(f"  - id: {json.dumps(i['id'])}")
    for k in ("source_section", "severity", "register_status", "finding", "corrective_action", "tests", "evidence", "residual_risk", "owner", "closure_decision", "human_signoff"):
        lines.append(f"    {k}: {json.dumps(i[k], ensure_ascii=False)}")
open(os.path.join(ROOT, "docs/release/REMEDIATION_REGISTER.yaml"), "w", encoding="utf-8").write("\n".join(lines) + "\n")
print(f"{len(items)} items: {len(open_items)} open/blocked/partial; ids: {', '.join(i['id'] for i in open_items)}")
